/**
 * List all workflow artifacts for the active workspace.
 */
export async function listArtifacts(req: Request, res: Response): Promise<void> {
  try {
    const workspaceId = req.workspaceId;
    if (!workspaceId) {
      res.status(401).json({ error: "Unauthorized" });
      return;
    }

    const { type, status, runId, limit = "50" } = req.query;

    const db = await getDb();
    if (!db) {
      res.status(503).json({ error: "Database unavailable" });
      return;
    }

    const conditions = [eq(workflowArtifacts.workspaceId, workspaceId)];

    if (type && typeof type === "string" && type !== "all") {
      conditions.push(eq(workflowArtifacts.artifactType, type));
    }
    if (status && typeof status === "string" && status !== "all") {
      conditions.push(eq(workflowArtifacts.status, status));
    }
    if (runId && typeof runId === "string") {
      conditions.push(eq(workflowArtifacts.workflowRunId, runId));
    }

    const artifacts = await db
      .select()
      .from(workflowArtifacts)
      .where(and(...conditions))
      .orderBy(desc(workflowArtifacts.createdAt))
      .limit(parseInt(limit as string, 10));

    res.status(200).json({
      workspaceId,
      artifacts,
      totalCount: artifacts.length,
    });
  } catch (error) {
    console.error("[Artifacts Controller Error]:", error);
    res.status(500).json({ error: "Failed to list artifacts" });
  }
}

/**
 * Get Content Calendar: specifically retrieves posts, drafts, and scheduled items formatted for calendar view.
 */
export async function getContentCalendar(req: Request, res: Response): Promise<void> {
  try {
    const workspaceId = req.workspaceId;
    if (!workspaceId) {
      res.status(401).json({ error: "Unauthorized" });
      return;
    }

    const db = await getDb();
    if (!db) {
      res.status(503).json({ error: "Database unavailable" });
      return;
    }

    // Query all post artifacts
    const postArtifacts = await db
      .select()
      .from(workflowArtifacts)
      .where(
        and(
          eq(workflowArtifacts.workspaceId, workspaceId),
          eq(workflowArtifacts.artifactType, "post")
        )
      )
      .orderBy(asc(workflowArtifacts.scheduledFor), desc(workflowArtifacts.createdAt))
      .limit(100);

    // Also check if local Content-Queue.md has active drafts to surface
    let localQueueSummary = "";
    const queuePath = path.resolve(process.cwd(), "Agent Lab LinkedIn", "Content-Queue.md");
    if (fs.existsSync(queuePath)) {
      try {
        localQueueSummary = fs.readFileSync(queuePath, "utf-8").substring(0, 10000);
      } catch (e) {
        console.warn("Could not read local Content-Queue.md:", e);
      }
    }

    res.status(200).json({
      workspaceId,
      calendarItems: postArtifacts,
      totalScheduled: postArtifacts.filter(a => a.status === "scheduled").length,
      totalDrafts: postArtifacts.filter(a => a.status === "draft").length,
      totalPublished: postArtifacts.filter(a => a.status === "published").length,
      localContentQueueExcerpt: localQueueSummary,
    });
  } catch (error) {
    console.error("[Content Calendar Controller Error]:", error);
    res.status(500).json({ error: "Failed to fetch content calendar" });
  }
}

